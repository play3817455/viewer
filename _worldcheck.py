def wstr(b, off, n):
    return b[off:off+n*2].decode('utf-16-le', errors='replace')

def load_hed(hedpath):
    with open(hedpath,'rb') as f: raw=f.read()
    psz=struct.unpack_from('<I',raw,8)[0]; nchunk=struct.unpack_from('<I',raw,12)[0]
    payload=bytearray(raw[16:16+psz])
    for i in range(len(payload)): payload[i]=(payload[i]-kHed[i%len(kHed)])&0xFF
    fmt=''; files=[]
    off=0
    for c in range(nchunk):
        t=struct.unpack_from('<I',payload,off)[0]; sz=struct.unpack_from('<I',payload,off+4)[0]; off+=8
        body=payload[off:off+sz]; off+=sz
        if t==1 and sz>=1:
            n=body[0]; fmt=wstr(body,1,n)
        elif t==3 and sz>=4:
            count=struct.unpack_from('<I',body,0)[0]; p=4
            for _ in range(count):
                nlen=body[p]; p+=1
                folder=wstr(body,p,nlen); p+=nlen*2
                plen=body[p]; p+=1
                path=''
                if plen:
                    path=wstr(body,p,plen); p+=plen*2
                volume=struct.unpack_from('<I',body,p)[0]; p+=4
                p+=8  # fileKey
                offset=struct.unpack_from('<I',body,p)[0]; p+=4
                size=struct.unpack_from('<I',body,p)[0]; p+=4
                p+=8  # hash
                files.append((folder,path,volume,offset,size))
    return fmt, files

def fmt_vol(fmt, volume):
    s = (fmt % volume) if '%' in fmt else fmt
    if len(s)>=2 and s[0]=='.' and (s[1]=='/' or s[1]=='\\'): s=s[2:]
    return s.replace('\\','/')

def vol_path(dataRoot, hedPath, fmt, volume):
    rel=fmt_vol(fmt, volume)
    name=os.path.basename(rel); parent=os.path.dirname(hedPath)
    stem=os.path.splitext(os.path.basename(hedPath))[0]
    for c in [os.path.join(dataRoot,rel), os.path.join(dataRoot,'data',rel),
              os.path.join(parent,name), os.path.join(parent,stem,name),
              os.path.join(parent,rel)]:
        if os.path.exists(c): return c
    return None

